//
// Pull already-verified layout/atom types from CollectiveBuilder (type-level only --
// this does not instantiate CUTLASS's own mainloop/kernel, just computes types).
//

// NOTE: the CollectiveBuilder's public ElementPairA/B must be the wrapped nv_float4_t<...>
// type (matching src/nvfp4_gemm.cu), NOT a raw cute::tuple<Element,SF> -- the latter also
// compiles (there's a blockscaled_type<..., cute::tuple<T,SF>> specialization) but computes
// SfVectorSize via a different, schedule-tag-driven path instead of nv_float4_t's fixed 16,
// which silently selected the wrong scale-factor vector size and corrupted the derived
// layouts / TMA descriptors.
using MainloopBuilder = cutlass::gemm::collective::CollectiveBuilder<
    cutlass::arch::Sm120, cutlass::arch::OpClassBlockScaledTensorOp,
    cutlass::nv_float4_t<ElementA>, LayoutATag, AlignmentA,
    cutlass::nv_float4_t<ElementB>, LayoutBTag, AlignmentB,
    ElementAccumulator, TileShape, ClusterShape,
    cutlass::gemm::collective::StageCountAutoCarveout<0>,  // no epilogue smem to carve out
    cutlass::gemm::collective::KernelScheduleAuto>;

using TiledMma = typename MainloopBuilder::TiledMma;
using Sm1xxBlkScaledConfig = typename MainloopBuilder::Sm1xxBlkScaledConfig;
constexpr int PipelineStages = MainloopBuilder::PipelineStages;

using SmemLayoutAtomA = typename MainloopBuilder::SmemLayoutAtomA;
using SmemLayoutAtomB = typename MainloopBuilder::SmemLayoutAtomB;
using SmemLayoutAtomSFA = typename MainloopBuilder::SmemLayoutAtomSFA;
using SmemLayoutAtomSFB = typename MainloopBuilder::SmemLayoutAtomSFB;
using SmemCopyAtomA = typename MainloopBuilder::SmemCopyAtomA;
using SmemCopyAtomB = typename MainloopBuilder::SmemCopyAtomB;
using SmemCopyAtomSFA = typename MainloopBuilder::SmemCopyAtomSFA;
using SmemCopyAtomSFB = typename MainloopBuilder::SmemCopyAtomSFB;
using GmemTiledCopyA = typename MainloopBuilder::GmemTiledCopyA;
using GmemTiledCopyB = typename MainloopBuilder::GmemTiledCopyB;
using GmemTiledCopySFA = typename MainloopBuilder::GmemTiledCopySFA;
using GmemTiledCopySFB = typename MainloopBuilder::GmemTiledCopySFB;

using StrideA = cutlass::gemm::TagToStrideA_t<LayoutATag>;
using StrideB = cutlass::gemm::TagToStrideB_t<LayoutBTag>;
using StrideC = cutlass::gemm::TagToStrideC_t<LayoutCTag>;
using StrideD = cutlass::gemm::TagToStrideC_t<LayoutDTag>;
using LayoutSFA = decltype(Sm1xxBlkScaledConfig::deduce_layoutSFA());
using LayoutSFB = decltype(Sm1xxBlkScaledConfig::deduce_layoutSFB());

// Full multi-stage smem layouts -- same construction CUTLASS's own sm120 blockscaled
// mainloop uses (include/cutlass/gemm/collective/sm120_blockscaled_mma_tma.hpp:185-215).
using SmemLayoutA = decltype(tile_to_shape(
    SmemLayoutAtomA{},
    make_shape(shape<0>(TileShape{}), shape<2>(TileShape{}), Int<PipelineStages>{}),
    conditional_t<cutlass::gemm::detail::is_major<0, StrideA>(), Step<_2, _1, _3>, Step<_1, _2, _3>>{}));
using SmemLayoutB = decltype(tile_to_shape(
    SmemLayoutAtomB{},
    make_shape(shape<1>(TileShape{}), shape<2>(TileShape{}), Int<PipelineStages>{}),
    conditional_t<cutlass::gemm::detail::is_major<0, StrideB>(), Step<_2, _1, _3>, Step<_1, _2, _3>>{}));

using SmemLayoutSFA = decltype(make_layout(
    append(shape(SmemLayoutAtomSFA{}), Int<PipelineStages>{}),
    append(stride(SmemLayoutAtomSFA{}), size(filter_zeros(SmemLayoutAtomSFA{})))));
using SmemLayoutSFB = decltype(make_layout(
    append(shape(SmemLayoutAtomSFB{}), Int<PipelineStages>{}),
    append(stride(SmemLayoutAtomSFB{}), size(filter_zeros(SmemLayoutAtomSFB{})))));
// (TileShape N == 128 here, so the "<128 broadcast" special case CUTLASS's mainloop
// handles for narrow-N tiles never triggers -- SmemLayoutSFB above is already final.)

static_assert(size<1>(TileShape{}) >= 128, "This file assumes TileShape N >= 128 (see SFB broadcast note above).");

constexpr bool IsF8F6F4 = false;  // size<2>(TiledMma::Shape_MNK) == 64 here, not 32; see cutlass/detail/collective.hpp is_sm120_f8f6f4().
using SmemAllocTypeA = cute::conditional_t<IsF8F6F4, uint8_t, typename TiledMma::ValTypeA>;
using SmemAllocTypeB = cute::conditional_t<IsF8F6F4, uint8_t, typename TiledMma::ValTypeB>;
// Since IsF8F6F4 is false here, these are just ElementA/ElementB; kept as named types (matching
// CUTLASS's own mainloop) since make_tma_copy needs a recast_ptr<TmaInternalElement...> cast below.
using TmaInternalElementA = ElementA;
using TmaInternalElementB = ElementB;

static constexpr uint32_t TmaTransactionBytesMK = static_cast<uint32_t>(
    cutlass::bits_to_bytes(cosize(take<0, 2>(SmemLayoutSFA{})) * cute::sizeof_bits_v<ElementSF>) +
    cutlass::bits_to_bytes(size(take<0, 2>(SmemLayoutA{})) * sizeof_bits<ElementA>::value));
static constexpr uint32_t TmaTransactionBytesNK = static_cast<uint32_t>(
    cutlass::bits_to_bytes(cosize(take<0, 2>(SmemLayoutSFB{})) * cute::sizeof_bits_v<ElementSF>) +
    cutlass::bits_to_bytes(size(take<0, 2>(SmemLayoutB{})) * sizeof_bits<ElementB>::value));
static constexpr uint32_t TmaTransactionBytes = TmaTransactionBytesMK + TmaTransactionBytesNK;

