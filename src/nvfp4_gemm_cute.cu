// Hand-written raw-CuTe NVFP4 (e2m1, block-scaled) GEMM for GeForce Blackwell (sm_120),
// D = alpha * A * B + beta * C.
//
// Unlike src/nvfp4_gemm.cu (which builds the kernel through CUTLASS's CollectiveBuilder),
// this file writes the TMA loads, the mainloop pipeline, the block-scaled MMA call, the
// producer/consumer warp-specialized kernel, and the epilogue ourselves -- using CuTe's
// layout/copy/mma primitives directly. Two categories of code are still reused verbatim
// from CUTLASS rather than hand-derived:
//   1. Pre-built hardware-wrapper library primitives with no connection to layout control
//      (cutlass::PipelineTmaAsync for mbarrier-based double buffering; cute::make_tma_copy;
//      the MMA_Traits<SM120::BLOCKSCALED::...> atom itself).
//   2. Type-level-only layout computations pulled from cutlass::gemm::collective::CollectiveBuilder
//      (SmemLayoutAtom[A,B,SFA,SFB], SmemCopyAtom[A,B], TiledMma, PipelineStages) -- these
//      encode intricate swizzle/stage-count arithmetic that CUTLASS engineers derived and
//      verified; referencing the types is like using cutlass::layout::RowMajor rather than
//      hand-deriving row-major stride arithmetic. No device code is generated by this --
//      CollectiveBuilder<...>::TiledMma etc. are just type aliases.
// The persistent tile scheduler uses a simple global-atomic-counter loop rather than
// CUTLASS's hardware Cluster-Launch-Control-based PersistentTileSchedulerSm100 -- that
// class wraps raw `clusterlaunchcontrol.*` PTX instructions, which has nothing to do with
// CuTe layout control and would add hardware-wrapper-transcription risk for no benefit.
// The epilogue is a simple direct-to-global store (no TMA store, no smem staging).

